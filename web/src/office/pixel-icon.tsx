export type PixelIconName = keyof typeof ICONS

export function PixelIcon({
  name,
  className,
}: {
  name: PixelIconName
  className?: string
}) {
  const rows = ICONS[name]
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 7 7"
      width={14}
      height={14}
      shapeRendering="crispEdges"
      className={className ?? "inline-block shrink-0"}
      fill="currentColor"
    >
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === "#" ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />
          ) : null
        )
      )}
    </svg>
  )
}
